CREATE OR REPLACE FUNCTION set_modified_date_time()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.modified_date_time := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS products (
    id UUID PRIMARY KEY,
    shop_id BIGINT NOT NULL REFERENCES shops (shop_id) ON DELETE CASCADE,
    category_id BIGINT REFERENCES product_categories (category_id),
    slug VARCHAR(150) NOT NULL,
    name_th VARCHAR(255) NOT NULL,
    name_en VARCHAR(255),
    name_zh VARCHAR(255),
    description_th TEXT,
    description_en TEXT,
    description_zh TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    product_type VARCHAR(30) NOT NULL DEFAULT 'SIMPLE',
    brand VARCHAR(100),
    base_price NUMERIC(18, 2),
    compare_at_price NUMERIC(18, 2),
    currency CHAR(3) NOT NULL DEFAULT 'THB',
    weight_grams INTEGER,
    published_at TIMESTAMPTZ,
    archived_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    created_date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by UUID,
    modified_date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by UUID,
    CONSTRAINT uq_products_shop_slug UNIQUE (shop_id, slug),
    CONSTRAINT ck_products_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    CONSTRAINT ck_products_type CHECK (product_type IN ('SIMPLE', 'VARIABLE')),
    CONSTRAINT ck_products_base_price CHECK (base_price IS NULL OR base_price >= 0),
    CONSTRAINT ck_products_compare_at_price CHECK (compare_at_price IS NULL OR compare_at_price >= 0)
);

CREATE INDEX IF NOT EXISTS idx_products_shop_status ON products (shop_id, status);

CREATE TABLE IF NOT EXISTS product_skus (
    id UUID PRIMARY KEY,
    product_id UUID NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    shop_id BIGINT NOT NULL REFERENCES shops (shop_id) ON DELETE CASCADE,
    sku_code VARCHAR(64) NOT NULL,
    barcode VARCHAR(64),
    option_label VARCHAR(255),
    option_values JSONB NOT NULL DEFAULT '{}'::jsonb,
    price NUMERIC(18, 2) NOT NULL,
    cost_price NUMERIC(18, 2),
    compare_at_price NUMERIC(18, 2),
    currency CHAR(3) NOT NULL DEFAULT 'THB',
    weight_grams INTEGER,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    deleted_at TIMESTAMPTZ,
    created_date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by UUID,
    modified_date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by UUID,
    CONSTRAINT uq_product_skus_shop_code UNIQUE (shop_id, sku_code),
    CONSTRAINT ck_product_skus_price CHECK (price >= 0),
    CONSTRAINT ck_product_skus_cost_price CHECK (cost_price IS NULL OR cost_price >= 0),
    CONSTRAINT ck_product_skus_compare_at_price CHECK (compare_at_price IS NULL OR compare_at_price >= 0)
);

CREATE INDEX IF NOT EXISTS idx_product_skus_product_id ON product_skus (product_id);

CREATE TABLE IF NOT EXISTS product_images (
    id UUID PRIMARY KEY,
    product_id UUID NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    storage_path VARCHAR(700) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    alt_text VARCHAR(255),
    created_date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by UUID,
    modified_date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by UUID
);

CREATE INDEX IF NOT EXISTS idx_product_images_product_id ON product_images (product_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_product_images_one_primary
    ON product_images (product_id)
    WHERE is_primary;

CREATE TABLE IF NOT EXISTS inventory_levels (
    id UUID PRIMARY KEY,
    shop_id BIGINT NOT NULL REFERENCES shops (shop_id) ON DELETE CASCADE,
    sku_id UUID NOT NULL REFERENCES product_skus (id) ON DELETE CASCADE,
    on_hand INTEGER NOT NULL DEFAULT 0,
    reserved_qty INTEGER NOT NULL DEFAULT 0,
    available INTEGER NOT NULL DEFAULT 0,
    low_stock_threshold INTEGER,
    version INTEGER NOT NULL DEFAULT 0,
    created_date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by UUID,
    modified_date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by UUID,
    CONSTRAINT uq_inventory_levels_sku UNIQUE (sku_id),
    CONSTRAINT ck_inventory_levels_on_hand CHECK (on_hand >= 0)
);

CREATE TABLE IF NOT EXISTS inventory_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id BIGINT NOT NULL REFERENCES shops (shop_id) ON DELETE CASCADE,
    sku_id UUID NOT NULL REFERENCES product_skus (id) ON DELETE CASCADE,
    entry_type VARCHAR(40) NOT NULL,
    quantity_delta INTEGER NOT NULL,
    on_hand_before INTEGER NOT NULL,
    on_hand_after INTEGER NOT NULL,
    reason VARCHAR(500),
    reference_type VARCHAR(40),
    reference_id VARCHAR(64),
    idempotency_key VARCHAR(100),
    actor_id UUID,
    created_date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by UUID,
    modified_date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modified_by UUID,
    CONSTRAINT uq_inventory_ledger_idempotency UNIQUE (idempotency_key),
    CONSTRAINT ck_inventory_ledger_adjust_reason CHECK (entry_type <> 'ADJUST' OR reason IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_inventory_ledger_sku_id ON inventory_ledger (sku_id);

DO $$
DECLARE
    table_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY['products', 'product_skus', 'product_images', 'inventory_levels', 'inventory_ledger']
    LOOP
        EXECUTE format(
            'DROP TRIGGER IF EXISTS %I ON %I',
            'trg_' || table_name || '_set_modified_date_time',
            table_name
        );
        EXECUTE format(
            'CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_modified_date_time()',
            'trg_' || table_name || '_set_modified_date_time',
            table_name
        );
    END LOOP;
END $$;
