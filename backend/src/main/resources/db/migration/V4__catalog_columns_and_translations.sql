-- Align the V1 catalog tables with the JPA entities.
--
-- Kept (do not recreate):
--   hub_categories          ProductCategory  (category_no + name_zh already added in V2)
--   products                Product          shop_id stays uuid -> shops.id
--   product_skus            ProductSku
--   product_images          ProductImage
--   inventory_levels        InventoryLevel
--   inventory_ledger        InventoryLedgerEntry
--   shops.category          Shop.category is the hub category name, not a bigint category_id
--
-- Added because V1 has no equivalent:
--   content_translations    ContentTranslation
--
-- products.name / products.description stay for the V1 shape. A BEFORE INSERT/UPDATE
-- trigger copies name_th / description_th into them so the NOT NULL name column is filled
-- when the application writes only the entity columns.
-- product_images.media_file_id stays as an optional link to media_files. The entity stores
-- the file at storage_path, so media_file_id is no longer required.
--
-- TSF_DB is empty at this version, so the column changes below are unconditional.
-- No IF NOT EXISTS: a mismatch must fail the migration.

-- -----------------------------------------------------------------------------
-- products — multilingual fields the Product entity writes, plus hub category
-- -----------------------------------------------------------------------------
ALTER TABLE products
    ADD COLUMN name_th character varying(255),
    ADD COLUMN name_en character varying(255),
    ADD COLUMN name_zh character varying(255),
    ADD COLUMN description_th text,
    ADD COLUMN description_en text,
    ADD COLUMN description_zh text,
    ADD COLUMN category_id uuid;

ALTER TABLE products
    ALTER COLUMN name_th SET NOT NULL;

ALTER TABLE products
    ADD CONSTRAINT fk_products_category_id
        FOREIGN KEY (category_id) REFERENCES hub_categories (id);

CREATE INDEX ix_products_category_id ON products USING btree (category_id);

COMMENT ON COLUMN products.name_th IS 'ชื่อสินค้าภาษาไทยที่ entity Product เขียน; products.name ของ V1 ถูกเติมจากคอลัมน์นี้';
COMMENT ON COLUMN products.category_id IS 'hub_categories.id (UUID). API ยังรับ category_no แล้วแปลงเป็นแถวนี้';

CREATE OR REPLACE FUNCTION sync_product_v1_display_columns()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.name IS NULL THEN
        NEW.name := NEW.name_th;
    END IF;
    IF NEW.description IS NULL THEN
        NEW.description := NEW.description_th;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_products_sync_v1_display
    BEFORE INSERT OR UPDATE ON products
    FOR EACH ROW EXECUTE FUNCTION sync_product_v1_display_columns();

-- -----------------------------------------------------------------------------
-- product_images — storage_path is what ProductImage persists
-- -----------------------------------------------------------------------------
ALTER TABLE product_images
    ALTER COLUMN media_file_id DROP NOT NULL;

ALTER TABLE product_images
    ADD COLUMN storage_path character varying(700) NOT NULL;

COMMENT ON COLUMN product_images.storage_path IS 'ไฟล์รูปที่ entity ProductImage บันทึก; media_file_id เป็นลิงก์เสริมไป media_files';

CREATE UNIQUE INDEX uq_product_images_one_primary
    ON product_images (product_id)
    WHERE is_primary;

-- -----------------------------------------------------------------------------
-- product_skus — option_values is NOT NULL on ProductSku
-- -----------------------------------------------------------------------------
ALTER TABLE product_skus
    ALTER COLUMN option_values SET NOT NULL;

-- -----------------------------------------------------------------------------
-- inventory_ledger — reference_id and idempotency_key match InventoryLedgerEntry
-- -----------------------------------------------------------------------------
ALTER TABLE inventory_ledger
    ALTER COLUMN reference_id TYPE character varying(64) USING reference_id::text;

ALTER TABLE inventory_ledger
    ALTER COLUMN idempotency_key TYPE character varying(100);

-- -----------------------------------------------------------------------------
-- content_translations — no V1 table
-- -----------------------------------------------------------------------------
CREATE TABLE content_translations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type character varying(50) NOT NULL,
    entity_id character varying(64) NOT NULL,
    field_name character varying(50) NOT NULL,
    locale character varying(10) NOT NULL,
    translated_text text,
    source_hash character varying(64),
    origin character varying(20) NOT NULL,
    status character varying(20) NOT NULL,
    provider character varying(30),
    error_message text,
    attempts integer DEFAULT 0 NOT NULL,
    created_date_time timestamp with time zone DEFAULT now() NOT NULL,
    created_by uuid,
    modified_date_time timestamp with time zone DEFAULT now() NOT NULL,
    modified_by uuid,
    CONSTRAINT uq_content_translations_entity UNIQUE (entity_type, entity_id, field_name, locale)
);

CREATE INDEX ix_content_translations_status ON content_translations USING btree (status);

CREATE TRIGGER trg_content_translations_modified_date_time
    BEFORE UPDATE ON content_translations
    FOR EACH ROW EXECUTE FUNCTION set_modified_date_time();

COMMENT ON TABLE content_translations IS 'คำแปลของสินค้า หมวดร้าน และชื่อร้าน (entity ContentTranslation)';
