package com.thaishopfun.merchant;

import com.thaishopfun.auth.UserAccount;
import jakarta.persistence.*;
import org.hibernate.annotations.Generated;

import java.time.Instant;
import java.util.UUID;

/**
 * Maps the V1 {@code shops} table (UUID primary key, tenant root). The public/API shop id is the
 * running number {@code shops.shop_no} (identity column added in V2) and is exposed as {@code shopId}
 * exactly like before. {@code owner_user_id} is the applicant account; {@code owner_id} links the KYC owner.
 */
@Entity
@Table(name = "shops", uniqueConstraints = @UniqueConstraint(name = "uq_shops_slug", columnNames = "slug"))
public class Shop {
    @Id private UUID id;
    @Generated
    @Column(name = "shop_no", insertable = false, updatable = false, columnDefinition = "bigint generated by default as identity")
    private Long shopId;
    @OneToOne(fetch = FetchType.LAZY) @JoinColumn(name = "application_id", unique = true) private MerchantApplication application;
    @ManyToOne(fetch = FetchType.LAZY, optional = false) @JoinColumn(name = "owner_user_id") private UserAccount user;
    @ManyToOne(fetch = FetchType.LAZY) @JoinColumn(name = "owner_id") private Owner owner;
    @Column(nullable = false, length = 150) private String name;
    @Column(name = "name_en", length = 150) private String nameEn;
    @Column(columnDefinition = "text") private String description;
    @Column(length = 100) private String category;
    @Enumerated(EnumType.STRING) @Column(name = "sale_type", length = 30) private SaleType saleType;
    @Column(length = 500) private String website;
    @Column(name = "line_id", length = 500) private String lineId;
    @Column(name = "facebook_url", length = 500) private String facebookUrl;
    @Column(name = "instagram_url", length = 500) private String instagramUrl;
    @Column(name = "tiktok_url", length = 500) private String tiktokUrl;
    /** Public storefront phone — not the owner's private contact. */
    @Column(name = "public_phone", length = 30) private String publicPhone;
    /** Public storefront email — not the owner's private contact. */
    @Column(name = "public_email") private String publicEmail;
    @Column(name = "logo_path", length = 500) private String logoPath;
    @Column(name = "cover_path", length = 500) private String coverPath;
    @Column(name = "opening_hours", length = 800) private String openingHours;
    @Column(name = "address_line", length = 500) private String address;
    @Column(length = 100) private String province;
    @Column(length = 100) private String district;
    @Column(length = 100) private String subdistrict;
    @Column(name = "postal_code", length = 10) private String postalCode;
    @Column(nullable = false, length = 100) private String slug;
    @Convert(converter = ShopStatusConverter.class) @Column(nullable = false, length = 30) private ShopStatus status;
    @Column(name = "published_at") private Instant publishedAt;
    @Column(name = "suspended_at") private Instant suspendedAt;
    @Column(name = "suspended_by") private UUID suspendedBy;
    @Column(name = "suspend_reason", columnDefinition = "text") private String suspendReason;
    @Column(name = "suspend_reason_code", length = 50) private String suspendReasonCode;
    @Column(name = "restored_at") private Instant restoredAt;
    @Column(name = "restored_by") private UUID restoredBy;
    @Column(name = "deleted_at") private Instant deletedAt;
    @Column(name = "created_date_time", nullable = false) private Instant createdAt;
    @Column(name = "modified_date_time", nullable = false) private Instant updatedAt;

    protected Shop() {}

    public Shop(MerchantApplication application, String slug, Owner owner) {
        var now = Instant.now();
        this.id = UUID.randomUUID();
        this.application = application;
        this.user = application.getUser();
        this.owner = owner;
        this.name = application.getShopName();
        this.nameEn = blankToNull(application.getShopNameEn());
        this.description = blankToNull(application.getShopDescription());
        this.category = application.getCategory();
        this.saleType = application.getSaleType();
        this.website = blankToNull(application.getWebsite());
        this.lineId = blankToNull(application.getLineId());
        this.facebookUrl = blankToNull(application.getFacebookUrl());
        this.instagramUrl = blankToNull(application.getInstagramUrl());
        this.tiktokUrl = blankToNull(application.getTiktokUrl());
        this.logoPath = application.getLogoPath();
        this.address = application.getShopAddress();
        this.province = application.getShopProvince();
        this.district = application.getShopDistrict();
        this.subdistrict = application.getShopSubdistrict();
        this.postalCode = application.getShopPostalCode();
        this.slug = slug;
        this.status = ShopStatus.PENDING_REVIEW;
        this.createdAt = now;
        this.updatedAt = now;
    }

    public String path() { return "/shop/" + slug; }

    public void approve() {
        status = ShopStatus.APPROVED;
        updatedAt = Instant.now();
        if (publishedAt == null) publishedAt = updatedAt;
        application.markApproved();
    }

    public void reject() {
        status = ShopStatus.REJECTED;
        updatedAt = Instant.now();
        application.markRejected();
    }

    public void suspend() {
        suspend(null, null, null);
    }

    /** Fills the V1 suspension columns (suspended_by / suspend_reason / suspend_reason_code) as well. */
    public void suspend(UUID actorId, String reason, String reasonCode) {
        status = ShopStatus.SUSPENDED;
        updatedAt = Instant.now();
        suspendedAt = updatedAt;
        suspendedBy = actorId;
        suspendReason = reason;
        suspendReasonCode = reasonCode;
    }

    public void reactivate() {
        reactivate(null);
    }

    public void reactivate(UUID actorId) {
        if (status != ShopStatus.SUSPENDED) {
            throw new IllegalStateException("เปิดใช้งานได้เฉพาะร้านที่ถูกระงับ");
        }
        status = ShopStatus.APPROVED;
        updatedAt = Instant.now();
        restoredAt = updatedAt;
        restoredBy = actorId;
    }

    public void updateSettings(
        String name,
        String nameEn,
        String description,
        String category,
        String website,
        String lineId,
        String facebookUrl,
        String instagramUrl,
        String tiktokUrl,
        String address,
        String province,
        String district,
        String subdistrict,
        String postalCode
    ) {
        this.name = name;
        this.nameEn = nameEn;
        this.description = description;
        this.category = category;
        this.website = website;
        this.lineId = lineId;
        this.facebookUrl = facebookUrl;
        this.instagramUrl = instagramUrl;
        this.tiktokUrl = tiktokUrl;
        this.address = address;
        this.province = province;
        this.district = district;
        this.subdistrict = subdistrict;
        this.postalCode = postalCode;
        this.updatedAt = Instant.now();
    }

    /** Update public storefront contact only. Blank strings clear the value (null). */
    public void updatePublicContact(String phone, String email) {
        this.publicPhone = blankToNull(phone == null ? null : phone.trim());
        this.publicEmail = blankToNull(email == null ? null : email.trim());
        this.updatedAt = Instant.now();
    }

    /** Public running shop number (shops.shop_no) used by the API as "shopId". */
    public Long getId() { return shopId; }
    /** Database primary key (shops.id). */
    public UUID getUuid() { return id; }
    public void assignSlug(String value) { this.slug = value; }
    public String getName() { return name; }
    public String getNameEn() { return nameEn; }
    public String getDescription() { return description; }
    public String getCategory() { return category; }
    public String getAddress() { return address; }
    public String getProvince() { return province; }
    public String getDistrict() { return district; }
    public String getSubdistrict() { return subdistrict; }
    public String getPostalCode() { return postalCode; }
    public String getSlug() { return slug; }
    public String getWebsite() { return website; }
    public String getLineId() { return lineId; }
    public String getFacebookUrl() { return facebookUrl; }
    public String getInstagramUrl() { return instagramUrl; }
    public String getTiktokUrl() { return tiktokUrl; }
    public String getPublicPhone() { return publicPhone; }
    public String getPublicEmail() { return publicEmail; }
    public ShopStatus getStatus() { return status; }
    public Instant getPublishedAt() { return publishedAt; }
    public Instant getSuspendedAt() { return suspendedAt; }
    public UUID getSuspendedBy() { return suspendedBy; }
    public String getSuspendReason() { return suspendReason; }
    public String getSuspendReasonCode() { return suspendReasonCode; }
    public Instant getRestoredAt() { return restoredAt; }
    public UUID getRestoredBy() { return restoredBy; }
    public Instant getCreatedAt() { return createdAt; }
    public Instant getUpdatedAt() { return updatedAt; }
    public UserAccount getUser() { return user; }
    public Owner getOwner() { return owner; }
    public MerchantApplication getApplication() { return application; }
    public void setCoverPath(String path) {
        this.coverPath = path;
        this.updatedAt = Instant.now();
    }

    public String getCoverPath() { return coverPath; }
    public String getOpeningHours() { return openingHours; }
    public void setOpeningHours(String value) {
        this.openingHours = value;
        this.updatedAt = Instant.now();
    }

    public String getOwnedLogoPath() { return logoPath; }
    public void setLogoPath(String path) {
        this.logoPath = path;
        this.updatedAt = Instant.now();
    }

    public String getLogoPath() {
        if (logoPath != null && !logoPath.isBlank()) return logoPath;
        return application == null ? null : application.getLogoPath();
    }

    private static String blankToNull(String value) { return value == null || value.isBlank() ? null : value; }
}
