CREATE TABLE merchant_applications (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    status VARCHAR(30) NOT NULL,
    reference_no VARCHAR(30) UNIQUE,
    shop_name VARCHAR(100),
    shop_name_en VARCHAR(100),
    shop_description VARCHAR(500),
    category VARCHAR(100),
    sale_type VARCHAR(30),
    website VARCHAR(500),
    logo_path VARCHAR(500),
    shop_address VARCHAR(500),
    shop_province VARCHAR(100),
    shop_district VARCHAR(100),
    shop_subdistrict VARCHAR(100),
    shop_postal_code VARCHAR(10),
    owner_type VARCHAR(30),
    owner_title VARCHAR(30),
    owner_first_name VARCHAR(100),
    owner_last_name VARCHAR(100),
    citizen_id_encrypted TEXT,
    birth_date DATE,
    nationality VARCHAR(100),
    owner_phone VARCHAR(30),
    owner_email VARCHAR(255),
    owner_house_no VARCHAR(50),
    owner_village_no VARCHAR(50),
    owner_building VARCHAR(255),
    owner_alley VARCHAR(255),
    owner_road VARCHAR(255),
    owner_province VARCHAR(100),
    owner_district VARCHAR(100),
    owner_subdistrict VARCHAR(100),
    owner_postal_code VARCHAR(10),
    bank_name VARCHAR(100),
    bank_account_encrypted TEXT,
    bank_account_name VARCHAR(255),
    submitted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE merchant_documents (
    id UUID PRIMARY KEY,
    application_id UUID NOT NULL REFERENCES merchant_applications(id) ON DELETE CASCADE,
    document_type VARCHAR(30) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    stored_filename VARCHAR(255) NOT NULL,
    storage_path VARCHAR(700) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_merchant_document_type UNIQUE(application_id, document_type)
);

CREATE INDEX idx_merchant_applications_status ON merchant_applications(status);

