package com.thaishopfun.merchant;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.hibernate.annotations.Generated;

import java.time.Instant;
import java.util.UUID;

/**
 * Shop categories offered on sign-up / store settings. Mapped onto the V1 {@code hub_categories} table
 * (shop categories of the hub) instead of a separate product_categories table. The numeric id the UI uses
 * is the running number {@code hub_categories.category_no} (identity column added in V2).
 */
@Entity
@Table(name = "hub_categories")
public class ProductCategory {
    @Id private UUID id;
    @Generated
    @Column(name = "category_no", insertable = false, updatable = false, columnDefinition = "bigint generated by default as identity")
    private Long categoryNo;
    @Column(nullable = false, unique = true, length = 100) private String slug;
    @Column(name = "name_th", nullable = false, length = 150) private String nameTh;
    @Column(name = "name_en", length = 150) private String nameEn;
    @Column(name = "name_zh", length = 150) private String nameZh;
    @Column(name = "sort_order", nullable = false) private int sortOrder;
    @Column(name = "is_active", nullable = false) private boolean active = true;
    @Column(name = "created_date_time", nullable = false) private Instant createdDateTime;
    @Column(name = "modified_date_time", nullable = false) private Instant modifiedDateTime;

    protected ProductCategory() {}

    public ProductCategory(String slug, String nameTh, String nameEn, String nameZh, int sortOrder) {
        var now = Instant.now();
        this.id = UUID.randomUUID();
        this.slug = slug;
        this.nameTh = nameTh;
        this.nameEn = nameEn;
        this.nameZh = nameZh;
        this.sortOrder = sortOrder;
        this.createdDateTime = now;
        this.modifiedDateTime = now;
    }

    /** Public numeric id (hub_categories.category_no). */
    public Long getId() { return categoryNo; }
    public UUID getUuid() { return id; }
    public String getSlug() { return slug; }
    public String getNameTh() { return nameTh; }
    public String getNameEn() { return nameEn; }
    public String getNameZh() { return nameZh; }
    public int getSortOrder() { return sortOrder; }
    public boolean isActive() { return active; }
}
